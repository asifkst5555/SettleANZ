</div>

<h2 id="short-term">Why Your First 2 to 4 Weeks Should Be in Short-Term Accommodation</h2>

<p>This is the single most consequential mistake I see new arrivals make and the one I made myself. Assuming you can move directly from the airport into a long-term rental within a week.</p>

<p>Book short-term accommodation for your first two to four weeks. Not as a contingency. As the actual plan. A serviced apartment or furnished short-stay gives you three things that are very difficult to put a price on in your first month:</p>

<ul>
    <li><strong>A real, verifiable address</strong> is essential for opening a bank account, applying for your Tax File Number, and beginning your job search. A friend's couch does not serve this purpose.</li>
    <li><strong>Time to search properly</strong>, so you can attend inspections, ask questions, and decline unsuitable properties without desperation shaping your decisions.</li>
    <li><strong>Mental space</strong>, mostly the difference between signing a bad 12-month lease under pressure and choosing the right property is almost always just time.</li>
</ul>

<p>Budget realistically. In Sydney or Melbourne, a decent short-stay runs between $120 and $250 AUD per night. Compare that to the cost of a rushed decision on a 12-month lease &mdash; a property with hidden issues you did not notice because you inspected it in ten anxious minutes.</p>

<div class="article-callout">
    <h3>Pro tip</h3>
